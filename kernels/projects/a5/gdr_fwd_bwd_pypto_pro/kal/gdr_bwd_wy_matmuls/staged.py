_PL_UINT64 = _dt_fix(pl.DT_UINT64)

@pl.vector_function
def form_kbeta(k, beta, kbeta, n, w):
    _tmp_maskreg_0 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    for kbr in pl.range(0, n, 1):
        b = vf.load_align(beta, kbr, dist=pl.LoadDist.BRC_B32)
        reg0 = vf.load_align(k, (kbr) * 128, dtype=_PL_FP32)
        reg1 = vf.load_align(k, (kbr) * 128 + 64, dtype=_PL_FP32)
        reg0 = vf.mul(reg0, b, _tmp_maskreg_0)
        reg1 = vf.mul(reg1, b, _tmp_maskreg_0)
        vf.store_align(kbeta + (kbr) * 128, reg0, _tmp_maskreg_0)
        vf.store_align(kbeta + (kbr) * 128 + 64, reg1, _tmp_maskreg_0)

@pl.vector_function
def glue1_strict_low(dA, n):
    _tmp_maskreg_0 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    mask = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    zero = vf.full(0.0, _tmp_maskreg_0, dtype=_PL_FP32)
    for g1r in pl.range(0, n, 1):
        reg = vf.load_align(dA, (g1r) * 64, dtype=_PL_FP32)
        mask = vf.update_mask(pl.max(0, g1r), dtype=_PL_FP32)
        out = vf.select(reg, zero, mask)
        vf.store_align(dA + (g1r) * 64, out, _tmp_maskreg_0)

@pl.vector_function
def glue2_decay_negate(dA, decay, n):
    _tmp_maskreg_0 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    mask = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    zero = vf.full(0.0, _tmp_maskreg_0, dtype=_PL_FP32)
    d_row = vf.load_align(decay, 0, dtype=_PL_FP32)
    for g2r in pl.range(0, n, 1):
        di = vf.load_align(decay, g2r, dist=pl.LoadDist.BRC_B32)
        gdiff = vf.sub(di, d_row, _tmp_maskreg_0)
        gdiff = vf.mins(gdiff, 0.0, _tmp_maskreg_0)
        ef = vf.exp(gdiff, _tmp_maskreg_0)
        reg = vf.load_align(dA, (g2r) * 64, dtype=_PL_FP32)
        reg = vf.mul(reg, ef, _tmp_maskreg_0)
        reg = vf.muls(reg, -1.0, _tmp_maskreg_0)
        mask = vf.update_mask(pl.max(0, g2r), dtype=_PL_FP32)
        out = vf.select(reg, zero, mask)
        vf.store_align(dA + (g2r) * 64, out, _tmp_maskreg_0)


