@pl.vector_function
def cast_vtile_vf(ub_v, ub_vf, vc, nvsub):
    active = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    for vr in pl.range(0, vc, 1):
        for vcb in pl.range(0, nvsub, 1):
            vsrc = vf.load_align(ub_v, (vr) * 128 + (vcb * 64), dist=pl.LoadDist.UNPK_B16)
            vfp = vf.astype(vsrc, active, dtype=_PL_FP32, layout=pl.CastLayout.ZERO)
            vf.store_align(ub_vf + (vr) * 128 + (vcb * 64), vfp, active)

@pl.vector_function
def decay_exp_vf(ub_dec, ub_dexp):
    _tmp_maskreg_0 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    active = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    zero = vf.full(0.0, active, dtype=_PL_FP32)
    d = vf.load_align(ub_dec, 0, dtype=_PL_FP32)
    de = vf.exp_sub(d, zero, active)
    vf.store_align(ub_dexp + 0, de, _tmp_maskreg_0)

@pl.vector_function
def decay_tail_vf(ub_dec, ub_dfac, ncsub):
    _tmp_maskreg_0 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    active = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    dlast = vf.load_align(ub_dec, 63, dist=pl.LoadDist.BRC_B32)
    for dc in pl.range(0, 64, 1):
        dc = vf.load_align(ub_dec, dc, dist=pl.LoadDist.BRC_B32)
        s = vf.exp_sub(dlast, dc, active)
        for dcb in pl.range(0, ncsub, 1):
            vf.store_align(ub_dfac + (dc) * 128 + (dcb * 64), s, _tmp_maskreg_0)

@pl.vector_function
def wy_forward_substitution_vf(ub_attn):
    _tmp_maskreg_0 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    active = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    one = vf.full(1.0, active, dtype=_PL_FP32)
    for fi in pl.range(1, 64, 1):
        acc = vf.full(0.0, active, dtype=_PL_FP32)
        for fm in pl.range(0, fi, 1):
            sc = vf.load_align(ub_attn, (fi) * 64 + fm, dist=pl.LoadDist.BRC_B32)
            row_m = vf.load_align(ub_attn, (fm) * 64, dtype=_PL_FP32)
            acc = vf.mul_add_dst(row_m, sc, active)
        old_i = vf.load_align(ub_attn, (fi) * 64, dtype=_PL_FP32)
        newi = vf.add(old_i, acc, active)
        vf.store_align(ub_attn + (fi) * 64, newi, _tmp_maskreg_0)
        vf.mem_bar(mode=pl.MemBarMode.VST_VLD)
    vf.mem_bar(mode=pl.MemBarMode.VST_VST)
    for fid in pl.range(0, 64, 1):
        vf.store_align(ub_attn + (fid) * 64 + fid, one, _tmp_maskreg_0, dist=pl.StoreDist.FIRST_ELEMENT)

@pl.vector_function
def decay_mask_vf(ub_dec, ub_L):
    _tmp_maskreg_1 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    _tmp_maskreg_0 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_INT32)
    active = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    zero = vf.full(0.0, active, dtype=_PL_FP32)
    cols = vf.arange(0, dtype=_PL_INT32, index_order=pl.IndexOrder.INCREASE_ORDER)
    dvec = vf.load_align(ub_dec, 0, dtype=_PL_FP32)
    for li in pl.range(0, 64, 1):
        di = vf.load_align(ub_dec, li, dist=pl.LoadDist.BRC_B32)
        lrow = vf.exp_sub(di, dvec, active)
        m = vf.create_mask(pattern=pl.MaskPattern.ALLF, dtype=_PL_INT32)
        m = vf.lt(cols, (li + 1), _tmp_maskreg_0)
        lrow = vf.select(lrow, zero, m)
        vf.store_align(ub_L + (li) * 64, lrow, _tmp_maskreg_1)

@pl.vector_function
def prep_scalars_vf(ub_bh, ub_gh, ub_bact, ub_gf, vc, h_idx):
    _tmp_maskreg_0 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    active = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    zero = vf.full(0.0, active, dtype=_PL_FP32)
    one = vf.full(1.0, active, dtype=_PL_FP32)
    for sr in pl.range(0, vc, 1):
        blog_bf = vf.load_align(ub_bh, (sr) * 32 + h_idx, dist=pl.LoadDist.BRC_B16)
        blog_f = vf.astype(blog_bf, active, dtype=_PL_FP32, layout=pl.CastLayout.ZERO)
        den = vf.exp_sub(zero, blog_f, active)
        den = vf.adds(den, 1.0, active)
        den = vf.div(one, den, active)
        vf.store_align(ub_bact + sr, den, _tmp_maskreg_0, dist=pl.StoreDist.FIRST_ELEMENT)
        gval = vf.load_align(ub_gh, (sr) * 32 + h_idx, dist=pl.LoadDist.BRC_B32)
        vf.store_align(ub_gf + sr, gval, _tmp_maskreg_0, dist=pl.StoreDist.FIRST_ELEMENT)

@pl.vector_function
def rowscale_vf(ub_src, ub_dexp, ub_dst, ncsub):
    _tmp_maskreg_0 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    active = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    for rc in pl.range(0, 64, 1):
        sc = vf.load_align(ub_dexp, rc, dist=pl.LoadDist.BRC_B32)
        for rcb in pl.range(0, ncsub, 1):
            row = vf.load_align(ub_src, (rc) * 128 + (rcb * 64), dtype=_PL_FP32)
            row = vf.mul(row, sc, active)
            vf.store_align(ub_dst + (rc) * 128 + (rcb * 64), row, _tmp_maskreg_0)

@pl.vector_function
def scale_ktile_vf(ub_q, ub_k, ub_bact, ub_qs, ub_kf, ub_kbeta, vc, ncsub, scale):
    active = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    for kr in pl.range(0, vc, 1):
        bs = vf.load_align(ub_bact, kr, dist=pl.LoadDist.BRC_B32)
        for kcb in pl.range(0, ncsub, 1):
            qsrc = vf.load_align(ub_q, (kr) * 128 + (kcb * 64), dist=pl.LoadDist.UNPK_B16)
            qf = vf.astype(qsrc, active, dtype=_PL_FP32, layout=pl.CastLayout.ZERO)
            qs = vf.muls(qf, scale, active)
            vf.store_align(ub_qs + (kr) * 128 + (kcb * 64), qs, active)
            ksrc = vf.load_align(ub_k, (kr) * 128 + (kcb * 64), dist=pl.LoadDist.UNPK_B16)
            kf = vf.astype(ksrc, active, dtype=_PL_FP32, layout=pl.CastLayout.ZERO)
            vf.store_align(ub_kf + (kr) * 128 + (kcb * 64), kf, active)
            kb = vf.mul(kf, bs, active)
            vf.store_align(ub_kbeta + (kr) * 128 + (kcb * 64), kb, active)

@pl.vector_function
def zero_fill_vf(ub_zero):
    active = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    z = vf.full(0.0, active, dtype=_PL_FP32)
    for zr in pl.range(0, 64, 1):
        for zcb in pl.range(0, 2, 1):
            vf.store_align(ub_zero + (zr) * 128 + (zcb * 64), z, active)


