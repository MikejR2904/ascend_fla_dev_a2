# The runner's older PyPTO build leaves gaps in its DT_* pybind
# coverage: some constants (DT_BF16 among them) arrive as bare ints
# that VF-layer kwarg checks reject ("expected ir::DataType, but got
# int"), while others on the same build are real DataType objects
# (add_rms_norm_dynamic_quant exercised FP16/FP32/INT8/INT16/UINT32
# there). Rebuild the broken ones from the enum value AT MODULE
# SCOPE -- the VF parser inlines helper calls and rejects
# isinstance, so the fixups must be plain names by the time a
# decorated body mentions them. A healthy build passes through.
_DTT = type(pl.DT_FP32)
def _dt_fix(v):
    return v if isinstance(v, _DTT) else _DTT(v)
_PL_BF16 = _dt_fix(pl.DT_BF16)
_PL_FP16 = _dt_fix(pl.DT_FP16)
_PL_FP32 = _dt_fix(pl.DT_FP32)
_PL_INT8 = _dt_fix(pl.DT_INT8)
_PL_INT16 = _dt_fix(pl.DT_INT16)
_PL_INT32 = _dt_fix(pl.DT_INT32)
_PL_INT64 = _dt_fix(pl.DT_INT64)
_PL_UINT8 = _dt_fix(pl.DT_UINT8)
_PL_UINT16 = _dt_fix(pl.DT_UINT16)
_PL_UINT32 = _dt_fix(pl.DT_UINT32)
_PL_UINT64 = _dt_fix(pl.DT_UINT64)

@pl.vector_function
def o_cast_vf(ub_o, ub_obf, vc, nvsub):
    _zero_fp32 = vf.full(0, dtype=_PL_FP32)
    _tmp_maskreg_0 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_BF16)
    for oar in pl.range(0, vc, 1):
        for oacb in pl.range(0, nvsub, 1):
            s = vf.load_align(ub_o, (oar) * 128 + (oacb * 64), dtype=_PL_FP32)
            bf = vf.astype(s, _tmp_maskreg_0, dtype=_PL_BF16, layout=pl.CastLayout.ZERO, round_mode=pl.VFRoundMode.CAST_RNA)
            _t1 = vf.xor(bf, _zero_fp32, _tmp_maskreg_0, dtype=_PL_FP32)
            vf.store_align(ub_obf + (oar) * 128 + (oacb * 64), _t1, _tmp_maskreg_0, dist=pl.StoreDist.PACK)

@pl.vector_function
def scan_sub_vf(ub_vprime, ub_uv, ub_dfac, ub_vscaled):
    _tmp_maskreg_0 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    for ssr in pl.range(0, 64, 1):
        fac = vf.load_align(ub_dfac, (ssr) * 8, dist=pl.LoadDist.BRC_B32)
        _r_u_regs_0_ = vf.load_align(ub_uv, (ssr) * 128, dtype=_PL_FP32)
        _r_u_regs_1_ = vf.load_align(ub_uv, (ssr) * 128 + 64, dtype=_PL_FP32)
        _r_vp_regs_0_ = vf.load_align(ub_vprime, (ssr) * 128, dtype=_PL_FP32)
        _r_vp_regs_1_ = vf.load_align(ub_vprime, (ssr) * 128 + 64, dtype=_PL_FP32)
        _r_vn_regs_0_ = vf.sub(_r_u_regs_0_, _r_vp_regs_0_, _tmp_maskreg_0)
        _r_vn_regs_1_ = vf.sub(_r_u_regs_1_, _r_vp_regs_1_, _tmp_maskreg_0)
        _r_vs_regs_0_ = vf.mul(_r_vn_regs_0_, fac, _tmp_maskreg_0)
        _r_vs_regs_1_ = vf.mul(_r_vn_regs_1_, fac, _tmp_maskreg_0)
        vf.store_align(ub_uv + (ssr) * 128, _r_vn_regs_0_, _tmp_maskreg_0)
        vf.store_align(ub_uv + (ssr) * 128 + 64, _r_vn_regs_1_, _tmp_maskreg_0)
        vf.store_align(ub_vscaled + (ssr) * 128, _r_vs_regs_0_, _tmp_maskreg_0)
        vf.store_align(ub_vscaled + (ssr) * 128 + 64, _r_vs_regs_1_, _tmp_maskreg_0)

@pl.vector_function
def state_update_vf(ub_state, ub_delta, ub_decay_exp, ck):
    _tmp_maskreg_0 = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    dreg = vf.load_align(ub_decay_exp, 63, dist=pl.LoadDist.BRC_B32)
    for sur in pl.range(0, ck, 1):
        _r_state_regs_0_ = vf.load_align(ub_state, (sur) * 128, dtype=_PL_FP32)
        _r_state_regs_1_ = vf.load_align(ub_state, (sur) * 128 + 64, dtype=_PL_FP32)
        _r_delta_regs_0_ = vf.load_align(ub_delta, (sur) * 128, dtype=_PL_FP32)
        _r_delta_regs_1_ = vf.load_align(ub_delta, (sur) * 128 + 64, dtype=_PL_FP32)
        _r_state_regs_0_ = vf.mul(_r_state_regs_0_, dreg, _tmp_maskreg_0)
        _r_state_regs_1_ = vf.mul(_r_state_regs_1_, dreg, _tmp_maskreg_0)
        _r_state_regs_0_ = vf.add(_r_state_regs_0_, _r_delta_regs_0_, _tmp_maskreg_0)
        _r_state_regs_1_ = vf.add(_r_state_regs_1_, _r_delta_regs_1_, _tmp_maskreg_0)
        vf.store_align(ub_state + (sur) * 128, _r_state_regs_0_, _tmp_maskreg_0)
        vf.mem_bar(mode=pl.MemBarMode.VST_VST)
        vf.store_align(ub_state + (sur) * 128 + 64, _r_state_regs_1_, _tmp_maskreg_0)
        vf.mem_bar(mode=pl.MemBarMode.VST_VLD)
        vf.mem_bar(mode=pl.MemBarMode.VST_VST)

@pl.vector_function
def zero_ub_vf(ub_t, nrows):
    active = vf.create_mask(pattern=pl.MaskPattern.ALL, dtype=_PL_FP32)
    z = vf.full(0.0, active, dtype=_PL_FP32)
    for zr in pl.range(0, nrows, 1):
        for zcb in pl.range(0, 2, 1):
            vf.store_align(ub_t + (zr) * 128 + (zcb * 64), z, active)


